"""Bundle local CommonJS modules without npm/build dependencies. Only siyuan is external."""
from pathlib import Path
import re
import json
root=Path(__file__).resolve().parents[1]
(root/'src/styles.js').write_text("/* Generated from gallery.css by scripts/build.py. */\n'use strict';\nmodule.exports="+json.dumps((root/'src/gallery.css').read_text(),ensure_ascii=False)+';\n')
names=['core','icons','styles','renderer']
def transform(code):
    def local(match):
        name=match[1]
        assert name in names, name
        return '__galleryRequire('+repr(name)+')'
    return re.sub(r"require\(['\"]\./([a-z]+)\.js['\"]\)",local,code)
modules=[]
for name in names:
    code=transform((root/'src'/f'{name}.js').read_text())
    modules.append(repr(name)+':function(module,exports){\n'+code+'\n}')
loader='''// Generated by scripts/build.py. Edit src/ then rebuild.
'use strict';
const __galleryFactories={MODULES};
const __galleryCache=Object.create(null);
function __galleryRequire(name){
 if(!__galleryCache[name]){const item={exports:{}};__galleryCache[name]=item;__galleryFactories[name](item,item.exports);}
 return __galleryCache[name].exports;
}
'''.replace('MODULES',',\n'.join(modules))
output=loader+transform((root/'src/index.js').read_text())
assert "require('./" not in output
(root/'dist').mkdir(exist_ok=True)
(root/'dist'/'index.js').write_text(output)
print('Built dist/index.js; only external module: siyuan')
